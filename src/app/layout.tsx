import type { Metadata, Viewport } from "next";
import { Azeret_Mono, Schibsted_Grotesk } from "next/font/google";
import { connection } from "next/server";

import { AppShell } from "@/components/app-shell";
import { SkipLink } from "@/components/skip-link";
import { getCurrentUser } from "@/lib/auth";
import { isLocalPreviewMode } from "@/lib/env";

import "./globals.css";
import "./components.css";
import "./responsive.css";
import "./motion-entry.css";
import "./motion-journal.css";
import "./motion-matrix.css";

const schibsted = Schibsted_Grotesk({
  subsets: ["latin"],
  weight: "variable",
  display: "swap",
  variable: "--font-soma-sans",
});

const azeretMono = Azeret_Mono({
  subsets: ["latin"],
  weight: "variable",
  display: "swap",
  variable: "--font-soma-mono",
});

export const metadata: Metadata = {
  title: {
    default: "Soma | Personal Lab",
    template: "Soma | %s",
  },
  applicationName: "Soma",
  description: "A personal lab for the relationships between health, focus, energy, recovery, and Deep Work.",
  icons: {
    icon: [{ url: "/icon.svg?v=erlenmeyer-2", type: "image/svg+xml" }],
    shortcut: ["/icon.svg?v=erlenmeyer-2"],
  },
  verification: {
    google: "vN4Hbw8JsncwAf_vQailk6Xw0Wrh7awEsPtmaVoJWL8",
  },
};

export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  colorScheme: "light",
  themeColor: "#F2EFE6",
};

export default async function RootLayout({ children }: Readonly<{ children: React.ReactNode }>) {
  // A fresh request is required so Next.js can attach the per-request CSP nonce
  // generated by proxy.ts to framework and hydration scripts.
  await connection();
  const user = await getCurrentUser();
  const localPreview = isLocalPreviewMode();

  return (
    <html className={`${schibsted.variable} ${azeretMono.variable}`} lang="en" data-scroll-behavior="smooth" suppressHydrationWarning>
      <body className={localPreview ? "local-preview" : undefined}>
        <SkipLink />
        {localPreview && <div className="preview-banner" role="status"><strong>LOCAL PREVIEW</strong><span>Demo Data · Nothing is sent or saved</span></div>}
        <AppShell user={user} localPreview={localPreview}>{children}</AppShell>
      </body>
    </html>
  );
}
